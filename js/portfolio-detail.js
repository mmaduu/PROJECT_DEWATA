// Get project ID from URL parameter
function getProjectId() {
    const urlParams = new URLSearchParams(window.location.search);
    return urlParams.get('project') || 'logo-design';
}

// Load project data
function loadProjectData() {
    const projectId = getProjectId();
    const project = portfolioData[projectId];

    if (!project) {
        // If project not found, redirect to portfolio page
        window.location.href = 'portfolio.html';
        return;
    }

    // Update page content
    document.getElementById('projectCategory').textContent = project.category;
    document.getElementById('projectTitle').textContent = project.title;
    document.getElementById('projectSubtitle').textContent = project.subtitle;
    document.getElementById('mainImage').src = project.mainImage;
    document.getElementById('mainImage').alt = project.title;
    document.getElementById('projectDescription').innerHTML = project.description;
    document.getElementById('sidebarCategory').textContent = project.category;

    // Update gallery
    const galleryGrid = document.querySelector('.gallery-grid');
    galleryGrid.innerHTML = '';
    project.gallery.forEach(imageSrc => {
        const galleryItem = document.createElement('div');
        galleryItem.className = 'gallery-item';
        galleryItem.innerHTML = `<img src="${imageSrc}" alt="Gallery Image">`;
        galleryGrid.appendChild(galleryItem);
    });

    // Update page title
    document.title = `${project.title} - DEWATA DIGITAL PRINT`;
}

// Initialize when DOM is loaded
document.addEventListener('DOMContentLoaded', loadProjectData);
